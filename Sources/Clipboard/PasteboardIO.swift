// MARK: - Snapshot

/// What was on the pasteboard at one change, read on the main thread.
struct PasteboardSnapshot {
    var types: [String] = []
    var string: String?
    var rtf: Data?
    var html: Data?
    var urlName: String?
    var fileURLs: [URL] = []
    var imageData: Data?
    var imageType: String?
    /// App-specific representations (kept so items paste back faithfully).
    var extras: [String: Data] = [:]
}

enum PasteboardTypes {
    /// Marks Bento's own writes from history so they are not recorded again.
    static let own = NSPasteboard.PasteboardType("com.charles.bento.clipboard")
    /// Dev only: lets test writes carry TransientType (so other clipboard
    /// managers skip them) while the dev harness still records them.
    static let devTest = "com.charles.bento.dev-test"
    static let urlName = NSPasteboard.PasteboardType("public.url-name")
    static let flatRTFD = NSPasteboard.PasteboardType("com.apple.flat-rtfd")

    /// nspasteboard.org markers and password-manager types: never record.
    static let ignored: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Image representations we store, in order of preference.
    static let images: [NSPasteboard.PasteboardType] = [
        .png, .tiff, NSPasteboard.PasteboardType(UTType.jpeg.identifier), NSPasteboard.PasteboardType(UTType.heic.identifier),
        NSPasteboard.PasteboardType(UTType.gif.identifier), NSPasteboard.PasteboardType(UTType.webP.identifier),
    ]

    /// Types handled explicitly (not archived as extras).
    static let standard: Set<String> = {
        var s: Set<String> = [
            NSPasteboard.PasteboardType.string.rawValue, NSPasteboard.PasteboardType.rtf.rawValue,
            NSPasteboard.PasteboardType.html.rawValue, NSPasteboard.PasteboardType.URL.rawValue,
            NSPasteboard.PasteboardType.fileURL.rawValue, urlName.rawValue, own.rawValue, devTest,
            "NSStringPboardType", "NeXT Rich Text Format v1.0 pasteboard type", "Apple HTML pasteboard type",
            "Apple URL pasteboard type", "CorePasteboardFlavorType 0x75726C20", "com.apple.pasteboard.promised-file-url",
            "public.utf16-external-plain-text", "public.utf16-plain-text", "com.apple.traditional-mac-plain-text",
            UTType.pdf.identifier, "com.adobe.pdf", "NSTIFFPboardType", "Apple PNG pasteboard type", "Apple PDF pasteboard type",
            "com.apple.icns", "public.file-url", "NSFilenamesPboardType",
        ]
        s.formUnion(images.map(\.rawValue))
        s.formUnion(ignored)
        return s
    }()
}

enum PasteboardReader {
    static let maxTextBytes = 10 * 1024 * 1024
    static let maxRichBytes = 8 * 1024 * 1024
    static let maxExtraBytes = 2 * 1024 * 1024
    static let maxExtrasTotal = 6 * 1024 * 1024

    /// Reads the pasteboard, or nil when this change must not be recorded
    /// (concealed/transient/auto-generated, Bento's own write, empty).
    static func read(_ pb: NSPasteboard, settings: ClipboardSettings, devMode: Bool = false) -> PasteboardSnapshot? {
        let types = pb.types ?? []
        let raw = Set(types.map(\.rawValue))
        if raw.contains(PasteboardTypes.own.rawValue) { return nil }
        var ignored = PasteboardTypes.ignored
        if devMode && raw.contains(PasteboardTypes.devTest) { ignored.remove("org.nspasteboard.TransientType") }
        if !raw.isDisjoint(with: ignored) { return nil }
        if types.isEmpty { return nil }

        var s = PasteboardSnapshot(types: types.map(\.rawValue))
        if settings.captureFiles, raw.contains(NSPasteboard.PasteboardType.fileURL.rawValue) {
            let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
            s.fileURLs = urls.filter(\.isFileURL)
            if !s.fileURLs.isEmpty { return s }
        }
        s.string = pb.string(forType: .string)
        if s.string == nil, let url = pb.string(forType: .URL) { s.string = url }
        if settings.captureRichText {
            s.rtf = pb.data(forType: .rtf).flatMap { $0.count <= maxRichBytes ? $0 : nil }
            s.html = pb.data(forType: .html).flatMap { $0.count <= maxRichBytes ? $0 : nil }
        }
        if s.string == nil, let rtf = s.rtf ?? pb.data(forType: .rtf) {
            s.string = NSAttributedString(rtf: rtf, documentAttributes: nil)?.string
        }
        s.urlName = pb.string(forType: PasteboardTypes.urlName)
        if settings.captureImages, let t = PasteboardTypes.images.first(where: { raw.contains($0.rawValue) }) {
            // Only read image bytes when the change is an image (not an office
            // app's picture of copied text).
            if ClipClassifier.prefersImage(string: s.string, hasRTF: s.rtf != nil) {
                s.imageData = pb.data(forType: t)
                s.imageType = t.rawValue
            }
        }
        if settings.captureRichText, s.imageData == nil, let item = pb.pasteboardItems?.first {
            var total = 0
            for t in item.types where !PasteboardTypes.standard.contains(t.rawValue) && !t.rawValue.hasPrefix("dyn.") {
                guard let d = item.data(forType: t), d.count <= maxExtraBytes, total + d.count <= maxExtrasTotal else { continue }
                s.extras[t.rawValue] = d
                total += d.count
            }
        }
        return s
    }
}

// MARK: - Classification

/// What a capture becomes. Images still need background processing.
enum PendingCapture {
    case ready(ClipDraft)
    case image(data: Data, type: String, hash: String)
}

enum ClipClassifier {
    /// An image wins over text only when the text is empty or just a URL
    /// (browsers put the image URL next to "Copy Image" data).
    static func prefersImage(string: String?, hasRTF: Bool) -> Bool {
        guard let s = string?.trimmingCharacters(in: .whitespacesAndNewlines), !s.isEmpty else { return true }
        return !hasRTF && ContentDetection.linkURL(s) != nil
    }

    static func classify(_ s: PasteboardSnapshot, settings: ClipboardSettings) -> PendingCapture? {
        if !s.fileURLs.isEmpty {
            guard settings.captureFiles else { return nil }
            let paths = s.fileURLs.map(\.path).joined(separator: "\n")
            return .ready(ClipDraft(kind: .file, text: paths, byteSize: paths.utf8.count, hash: hash("file", paths)))
        }
        if let data = s.imageData, let type = s.imageType, settings.captureImages, !data.isEmpty {
            guard data.count <= settings.maxImageMB * 1024 * 1024 else { return nil }
            return .image(data: data, type: type, hash: hash(data))
        }
        guard settings.captureText, let text = s.string,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= PasteboardReader.maxTextBytes else { return nil }
        let kind = ContentDetection.kind(forText: text)
        var d = ClipDraft(kind: kind, text: text, hash: hash("text", text))
        if settings.captureRichText {
            d.rtf = s.rtf
            d.html = s.html
            if !s.extras.isEmpty {
                d.extras = try? PropertyListSerialization.data(fromPropertyList: s.extras, format: .binary, options: 0)
            }
        }
        if kind == .link {
            let t = (s.urlName ?? ContentDetection.anchorTitle(html: s.html))?.trimmingCharacters(in: .whitespacesAndNewlines)
            if let t, !t.isEmpty, t != text.trimmingCharacters(in: .whitespacesAndNewlines) { d.linkTitle = t }
        }
        d.byteSize = text.utf8.count + (d.rtf?.count ?? 0) + (d.html?.count ?? 0) + (d.extras?.count ?? 0)
        return .ready(d)
    }

    static func hash(_ prefix: String, _ text: String) -> String { hash(Data((prefix + ":" + text).utf8)) }

    static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).prefix(16).map { String(format: "%02x", $0) }.joined()
    }
}

// MARK: - Writing

enum PasteboardWriter {
    /// Puts a history entry on the pasteboard. `plain` drops formatting
    /// (files become their paths). Returns false if there was nothing to write.
    @discardableResult
    static func write(_ d: ClipDetail, plain: Bool, store: ClipStore, to pb: NSPasteboard = .general) -> Bool {
        var items: [NSPasteboardItem] = []
        switch d.kind {
        case .text, .link, .color:
            guard let text = d.text else { return false }
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            if !plain {
                if let rtf = d.rtf { item.setData(rtf, forType: .rtf) }
                if let html = d.html { item.setData(html, forType: .html) }
                if let extras = d.extras,
                   let dict = try? PropertyListSerialization.propertyList(from: extras, format: nil) as? [String: Data] {
                    for (t, data) in dict { item.setData(data, forType: NSPasteboard.PasteboardType(t)) }
                }
                if d.kind == .link, let url = ContentDetection.linkURL(text) {
                    item.setString(url.absoluteString, forType: .URL)
                    if let title = d.linkTitle { item.setString(title, forType: PasteboardTypes.urlName) }
                }
            }
            items = [item]
        case .image:
            guard let url = store.imageURL(d.imageFile), let data = try? Data(contentsOf: url) else { return false }
            let item = NSPasteboardItem()
            let type = NSPasteboard.PasteboardType(d.imageType ?? NSPasteboard.PasteboardType.png.rawValue)
            item.setData(data, forType: type)
            if type != .tiff {
                // Older apps only read TIFF; convert only if someone asks.
                let provider = TIFFProvider(url: url)
                TIFFProvider.current = provider
                item.setDataProvider(provider, forTypes: [.tiff])
            }
            items = [item]
        case .file:
            let urls = d.fileURLs
            guard !urls.isEmpty else { return false }
            if plain {
                let item = NSPasteboardItem()
                item.setString(urls.map(\.path).joined(separator: "\n"), forType: .string)
                items = [item]
            } else {
                items = urls.map { url in
                    let item = NSPasteboardItem()
                    item.setString(url.absoluteString, forType: .fileURL)
                    item.setString(url.lastPathComponent, forType: .string)
                    return item
                }
            }
        }
        for item in items { item.setData(Data(), forType: PasteboardTypes.own) }
        pb.clearContents()
        return pb.writeObjects(items)
    }

    /// Replaces the pasteboard with its plain-text content (for "Paste as Plain Text").
    @discardableResult
    static func stripFormatting(_ pb: NSPasteboard = .general) -> Bool {
        guard let s = pb.string(forType: .string) else { return false }
        let item = NSPasteboardItem()
        item.setString(s, forType: .string)
        item.setData(Data(), forType: PasteboardTypes.own)
        pb.clearContents()
        return pb.writeObjects([item])
    }
}

private final class TIFFProvider: NSObject, NSPasteboardItemDataProvider {
    static var current: TIFFProvider?
    let url: URL
    init(url: URL) { self.url = url }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        if let tiff = NSImage(contentsOf: url)?.tiffRepresentation { item.setData(tiff, forType: .tiff) }
    }

    func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {
        if TIFFProvider.current === self { TIFFProvider.current = nil }
    }
}

// MARK: - Monitor

/// Watches `NSPasteboard.general.changeCount`. There is no change
/// notification on macOS, so this is the one timer Bento allows: 2 Hz with
/// generous tolerance so the system can coalesce wake-ups.
final class PasteboardMonitor {
    private let pb: NSPasteboard
    private var timer: Timer?
    private var lastChange: Int
    var onChange: ((NSPasteboard) -> Void)?

    init(pasteboard: NSPasteboard = .general) {
        pb = pasteboard
        lastChange = pasteboard.changeCount
    }

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        lastChange = pb.changeCount // changes made while stopped are not recorded
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.tick() }
        t.tolerance = 0.3
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call right after writing to the pasteboard ourselves.
    func skipCurrentChange() { lastChange = pb.changeCount }

    private func tick() {
        let c = pb.changeCount
        guard c != lastChange else { return }
        lastChange = c
        onChange?(pb)
    }
}

#!/usr/bin/env python3
"""Writes UnicodeTables.kt from tables.json (Tables.swift, run on a Mac).

    gen_tables.py tables.json out/UnicodeTables.kt
"""
import json
import sys

FINAL = "abcdefghijklmnopqrstuvwxyz012345"
CONT = "ABCDEFGHIJKLMNOPQRSTUVWXYZ6789!#"

# Swift's Unicode._GraphemeBreakProperty (0: any)
SWIFT_CLASSES = ["control", "extend", "extendedPictographic", "l", "lv", "lvt", "prepend", "regionalIndicator", "spacingMark", "t", "v", "zwj"]


def num(n):
    assert n >= 0
    digits = []
    while True:
        digits.append(n & 31)
        n >>= 5
        if n == 0:
            break
    digits.reverse()
    return "".join(CONT[d] for d in digits[:-1]) + FINAL[digits[-1]]


def encode(ranges, values=None):
    """Ranges as (gap from the previous end, length - 1[, value]) numbers."""
    out = []
    prev = -1
    for i, (a, b) in enumerate(ranges):
        out.append(num(a - prev - 1))
        out.append(num(b - a))
        if values is not None:
            out.append(num(values[i]))
        prev = b
    return "".join(out)


def merge(classified):
    """[(start, end, value)] sorted, adjacent equal values joined."""
    classified.sort()
    out = []
    for a, b, v in classified:
        if out and out[-1][2] == v and out[-1][1] + 1 == a:
            out[-1] = (out[-1][0], b, v)
        else:
            out.append((a, b, v))
    return out


def const(name):
    out = ""
    for ch in name:
        if ch.isupper():
            out += "_"
        out += ch.upper()
    return out


def main():
    tables_path, out_path = sys.argv[1:3]
    t = json.load(open(tables_path))
    swift = t["swiftGraphemeBreak"]
    gcb = merge([(a, b, SWIFT_CLASSES.index(name) + 1) for name in SWIFT_CLASSES for a, b in swift[name]])
    icu = t["icuGraphemeClusterBreak"]

    def flat(rs):
        return encode([tuple(r) for r in rs])

    def table(name, rs, doc):
        return [f"    /** {doc} */", f'    val {name}: IntArray by lazy {{ decode("{flat(rs)}", 2) }}']

    lines = [
        "// Generated by android/core/xcheck/notes/tables/gen_tables.py from the Mac (Tables.swift): do not edit.",
        f"// Swift's grapheme data, ICU {t['icuUnicodeVersion']} properties and CoreFoundation's character sets.",
        "package com.charles.bento.core.notes",
        "",
        "/** Code point ranges the Mac's string code works with (see Tables.swift). */",
        "internal object UnicodeTables {",
        "    // Swift's Unicode._GraphemeBreakProperty values (0: any)",
        *[f"    const val GB_{const(n)} = {i + 1}" for i, n in enumerate(SWIFT_CLASSES)],
        "",
        "    /** Swift's grapheme break classes, as (start, end, class) triples. */",
        f'    val swiftGraphemeBreak: IntArray by lazy {{ decode("{encode([(a, b) for a, b, _ in gcb], [v for _, _, v in gcb])}", 3) }}',
        *table("swiftInCBConsonant", t["swiftInCBConsonant"], "Swift's InCB=Consonant (GB9c)."),
        *table("extendedPictographic", t["icuExtendedPictographic"], "ICU: Extended_Pictographic."),
        *table("graphemeExtend", t["icuGraphemeExtend"], "ICU: Grapheme_Extend."),
        *table("emojiModifier", t["icuEmojiModifier"], "ICU: Emoji_Modifier."),
        *table("icuPrepend", icu["Prepend"], "ICU: Grapheme_Cluster_Break=Prepend."),
        *table("icuSpacingMark", icu["SpacingMark"], "ICU: Grapheme_Cluster_Break=SpacingMark."),
        *table("cfNonBase", t["cfNonBase"], "CharacterSet.nonBaseCharacters."),
        *table("cfLetters", t["cfLetters"], "CharacterSet.letters."),
        *table("cfWhitespaces", t["cfWhitespaces"], "CharacterSet.whitespaces."),
        *table("cfWhitespacesAndNewlines", t["cfWhitespacesAndNewlines"], "CharacterSet.whitespacesAndNewlines."),
        *table("cfAlphanumerics", t["cfAlphanumerics"], "CharacterSet.alphanumerics."),
        *table("viramas", t["swiftVirama"], "Canonical combining class 9."),
        *table("whiteSpace", t["swiftWhiteSpace"], "White_Space."),
        "",
        "    fun contains(table: IntArray, cp: Int): Boolean = find(table, 2, cp) >= 0",
        "",
        "    /** The value of the range containing `cp` in a table of (start, end, value) triples, 0 when none. */",
        "    fun value(table: IntArray, cp: Int): Int = find(table, 3, cp).let { if (it < 0) 0 else table[it + 2] }",
        "",
        "    private fun find(table: IntArray, stride: Int, cp: Int): Int {",
        "        var lo = 0",
        "        var hi = table.size / stride - 1",
        "        while (lo <= hi) {",
        "            val mid = (lo + hi) ushr 1",
        "            val i = mid * stride",
        "            when {",
        "                cp < table[i] -> hi = mid - 1",
        "                cp > table[i + 1] -> lo = mid + 1",
        "                else -> return i",
        "            }",
        "        }",
        "        return -1",
        "    }",
        "",
        "    private const val FINAL = \"" + FINAL + "\"",
        "    private const val CONT = \"" + CONT + "\"",
        "",
        "    /** Ranges written as (gap after the previous end, length - 1[, value]) base-32 numbers. */",
        "    private fun decode(s: String, stride: Int): IntArray {",
        "        val nums = ArrayList<Int>()",
        "        var acc = 0",
        "        for (c in s) {",
        "            val f = FINAL.indexOf(c)",
        "            if (f >= 0) {",
        "                nums.add(acc * 32 + f)",
        "                acc = 0",
        "            } else {",
        "                acc = acc * 32 + CONT.indexOf(c)",
        "            }",
        "        }",
        "        val out = IntArray(nums.size)",
        "        var prev = -1",
        "        var i = 0",
        "        while (i < nums.size) {",
        "            val start = prev + 1 + nums[i]",
        "            val end = start + nums[i + 1]",
        "            out[i] = start",
        "            out[i + 1] = end",
        "            if (stride == 3) out[i + 2] = nums[i + 2]",
        "            prev = end",
        "            i += stride",
        "        }",
        "        return out",
        "    }",
        "}",
        "",
    ]
    open(out_path, "w", encoding="utf-8").write("\n".join(lines))


main()

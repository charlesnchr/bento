// Renders the call's two tones once, as Android's CallEarcons.kt does, into src/earcons.ts.
// They're constants so every engine plays the same bytes (Math.sin isn't bit-identical across engines).
import { writeFileSync } from "node:fs";

const RATE = 24000, PEAK = 0.15;
function render(seconds, notes) {
  const samples = Math.round(seconds * RATE);
  const out = Buffer.alloc(samples * 2);
  for (let i = 0; i < samples; i++) {
    const t = i / RATE;
    let v = 0;
    for (const n of notes) {
      const u = t - n.at;
      if (u < 0 || u >= n.length) continue;
      const attack = Math.min(1, u / 0.005);
      const decay = Math.exp(-4 * u / n.length) * (1 - u / n.length);
      v += (Math.sin(2 * Math.PI * n.hz * u) + 0.25 * Math.sin(4 * Math.PI * n.hz * u)) / 1.25 * attack * decay;
    }
    const s = Math.max(-32768, Math.min(32767, Math.round(v * PEAK * 32767)));
    out.writeInt16LE(s, 2 * i);
  }
  return out.toString("base64");
}
const started = render(0.11, [{ at: 0, length: 0.11, hz: 880 }]);
const result = render(0.27, [{ at: 0, length: 0.12, hz: 660 }, { at: 0.13, length: 0.14, hz: 990 }]);
writeFileSync(new URL("../src/earcons.ts", import.meta.url),
`// Generated by scripts/gen-earcons.mjs: the tones of Android's CallEarcons.kt, 24 kHz PCM16 mono, base64.
// A task started: one soft blip at 880 Hz. A result arrived: 660 Hz then 990 Hz, rising.

export const TASK_STARTED = "${started}";
export const RESULT_ARRIVED = "${result}";
`);

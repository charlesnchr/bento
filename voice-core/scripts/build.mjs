// Builds dist/voice-core.js: one ES2020 script that sets globalThis.VoiceCore, for every host.
// `--watch` rebuilds on change (the dev server uses `build()` directly).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
export const OUT = root + "dist/voice-core.js";

/** Builds the bundle; its version is a hash of what it does, so a host can show which core it runs. */
export async function build() {
  const first = await esbuild.build({
    entryPoints: [root + "src/index.ts"],
    bundle: true,
    format: "iife",
    target: "es2020",
    write: false,
    legalComments: "none",
    define: { __VERSION__: '"@VOICE_CORE_VERSION@"' },
  });
  const body = first.outputFiles[0].text;
  const version = createHash("sha256").update(body).digest("hex").slice(0, 12);
  const header = `// Bento voice core ${version}. Generated by voice-core/scripts/build.mjs from voice-core/src: edit those, then npm run build.\n`;
  const text = header + body.replaceAll("@VOICE_CORE_VERSION@", version);
  mkdirSync(root + "dist", { recursive: true });
  let old = "";
  try { old = readFileSync(OUT, "utf8"); } catch {}
  if (old !== text) writeFileSync(OUT, text);
  // Every build is kept by version, so the replay view can run a trace through the build that recorded it.
  mkdirSync(root + "dist/versions", { recursive: true });
  writeFileSync(root + `dist/versions/${version}.js`, text);
  return { version, changed: old !== text };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { version, changed } = await build();
  console.log(`dist/voice-core.js ${version}${changed ? "" : " (unchanged)"}`);
}
